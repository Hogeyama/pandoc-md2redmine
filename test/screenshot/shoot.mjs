// Saves a screenshot of each case's wiki page next to its golden file, and
// writes test/cases/README.md, which shows them all with their descriptions.
import { chromium } from 'playwright';
import { readFileSync, writeFileSync } from 'node:fs';

const base = process.env.REDMINE_URL;
const groups = JSON.parse(readFileSync('/cases/cases.json', 'utf8'));
const browser = await chromium.launch();
const page = await browser.newPage({ viewport: { width: 960, height: 600 } });

for (const { cases } of groups) {
  for (const { name } of cases) {
    await page.goto(`${base}/projects/cases/wiki/${name}`);
    // Open every {{collapse}}, including ones that an opened one reveals.
    const closed = page.locator('div.wiki-page a.collapsible.icon-collapsed:visible');
    while (await closed.count() > 0) {
      await closed.first().click();
      await page.waitForFunction(() => jQuery(':animated').length === 0);
    }
    // Keep the last clicked link from showing its hover style.
    await page.mouse.move(0, 0);
    // mermaid marks each diagram it has rendered with data-processed.
    await page.waitForFunction(() =>
      [...document.querySelectorAll('.mermaid')].every(e => e.dataset.processed));
    await page.locator('div.wiki-page').screenshot({ path: `/cases/${name}/redmica.png` });
    console.log(name);
  }
}
await browser.close();

const escape = s => s.replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;');
const lines = [
  '<!-- Generated by `make screenshots` from cases.json. Do not edit. -->',
  '',
  '# Test cases',
  '',
  'How RedMica 3.1.7 with RedMica UI Extension v0.6.0 renders the `golden` of each case.',
];
for (const { title, cases } of groups) {
  lines.push('', `## ${escape(title)}`);
  for (const { name, description } of cases) {
    lines.push(
      '',
      `### ${name}: ${escape(description)}`,
      '',
      `[input.md](${name}/input.md) · [golden](${name}/golden)`,
      '',
      `![${name} on RedMica](${name}/redmica.png)`,
    );
  }
}
writeFileSync('/cases/README.md', lines.join('\n') + '\n');
